#!/usr/bin/env python3
"""Embed the Odin-Multi apical target PDBs into the Kaggle kernel script.

Why this exists
---------------
`kaggle/odin_multi_tfr1_smoke/kernel-metadata.json` declares `kernel_type: script`.
For a script kernel, `kaggle kernels push -p DIR` uploads ONLY the file named by
`code_file`. Every other file in the directory -- including the two target PDBs --
is silently left behind. The 2026-10-29 smoke therefore died with

    FileNotFoundError: '/kaggle/src/human_tfr1_apical_189_383.pdb'

after ~12 minutes of conda environment installation.

Why embedding rather than a dataset or a URL fetch
-------------------------------------------------
* The repository is PRIVATE, so `raw.githubusercontent.com` cannot be used without
  shipping a GitHub token into a third-party notebook. That is not acceptable.
* `mouse_tfr1_apical_homolog.pdb` is a curated homology model that exists only in
  this repository. Unlike the human crop it CANNOT be regenerated from RCSB, so the
  proven `urllib.request.urlretrieve(... files.rcsb.org ...)` pattern used by
  `kaggle/freebindcraft_v6_tempered_binary` and `kaggle/rfdiffusion_pilot_v1`
  does not cover it.
* Embedding the bytes in `code_file` is the only mechanism that is guaranteed to
  arrive, needs no credentials, no network and no new external asset, and keeps the
  curated coordinates byte-exact (verified by SHA-256 inside the kernel).

Re-run this script after changing either PDB:

    python scripts/embed_odin_multi_targets.py
"""

from __future__ import annotations

import base64
import gzip
import hashlib
import textwrap
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KDIR = ROOT / "kaggle/odin_multi_tfr1_smoke"
SCRIPT = KDIR / "tfr1_odin_multi_smoke.py"

TARGETS = [
    "human_tfr1_apical_189_383.pdb",
    "mouse_tfr1_apical_homolog.pdb",
]

BEGIN = "# --- BEGIN EMBEDDED TARGETS (generated by scripts/embed_odin_multi_targets.py) ---"
END = "# --- END EMBEDDED TARGETS ---"


def build_block() -> str:
    lines = [
        BEGIN,
        "# Regenerate with: python scripts/embed_odin_multi_targets.py",
        "# Script kernels upload only `code_file`, so the targets travel inside it.",
        "EMBEDDED_TARGET_SHA256={",
    ]
    payloads = {}
    for name in TARGETS:
        raw = (KDIR / name).read_bytes()
        digest = hashlib.sha256(raw).hexdigest()
        lines.append(f'    "{name}":"{digest}",')
        payloads[name] = base64.b64encode(gzip.compress(raw, 9)).decode("ascii")
    lines.append("}")
    lines.append("")
    lines.append("EMBEDDED_TARGET_GZ_B64={")
    for name, blob in payloads.items():
        lines.append(f'    "{name}":(')
        for chunk in textwrap.wrap(blob, 100):
            lines.append(f'        "{chunk}"')
        lines.append("    ),")
    lines.append("}")
    lines.append(END)
    return "\n".join(lines) + "\n"


def main() -> None:
    text = SCRIPT.read_text()
    block = build_block()

    if BEGIN in text and END in text:
        head, rest = text.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        text = head + block.rstrip("\n") + tail
    else:
        raise SystemExit(
            f"Markers not found in {SCRIPT}. Insert:\n{BEGIN}\n{END}\nfirst."
        )

    SCRIPT.write_text(text)
    print(f"Embedded {len(TARGETS)} targets into {SCRIPT.relative_to(ROOT)}")
    for name in TARGETS:
        raw = (KDIR / name).read_bytes()
        print(f"  {name}: {len(raw)} bytes raw, sha256={hashlib.sha256(raw).hexdigest()[:16]}...")
    print(f"  script now {SCRIPT.stat().st_size} bytes")

if __name__ == "__main__":
    main()
