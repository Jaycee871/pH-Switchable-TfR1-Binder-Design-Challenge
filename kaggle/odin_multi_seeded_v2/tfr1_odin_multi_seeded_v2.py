def patch_odin_warm_start():
    """Warm-start the shared multi-context sequence from the validated v6 parent.

    Odin/ColabDesign evaluates auxiliary target contexts with the same params["seq"],
    so restarting the main design model with this sequence initializes every target
    context from one shared binder sequence. The patch is deliberately inserted only
    after all target contexts have been prepared and before campaign loss weights are set.
    """
    path=ODIN/"functions/colabdesign_utils.py"
    text=path.read_text()
    old='''    if aux_params_list:
        af_model.prep_offtarget_inputs(aux_params_list)

    af_model._args["gradient_weight"] = float(main_advanced["gradient_weight"])
'''
    new=f'''    if aux_params_list:
        af_model.prep_offtarget_inputs(aux_params_list)

    warm_start_seq = "SPSVISTTTTTYTYHGKQVTRIRTTINPGEKIEPAPGERQMRGRDWETGYIIVHTYKVNS"
    if len(warm_start_seq) != length:
        raise ValueError(f"Warm-start length {{len(warm_start_seq)}} != requested binder length {{length}}")
    print(f"[WARM START] shared binder initialized from FreeBindCraft v6 sequence ({{length}} aa)")
    af_model.restart(seed=seed, seq=warm_start_seq)

    af_model._args["gradient_weight"] = float(main_advanced["gradient_weight"])
'''
    if old not in text:
        raise RuntimeError("Odin warm-start insertion point not found; refusing unverified patch")
    path.write_text(text.replace(old,new,1))
    (OUT/"odin_warm_start_patch.txt").write_text(
        "Inserted af_model.restart(seed=seed, seq=V6_WARM_START_SEQUENCE) after multi-context prep.\n"
        "Shared sequence: "+V6_WARM_START_SEQUENCE+"\n"
    )
    print("Patched Odin-Multi for shared v6 sequence warm-start.",flush=True)


