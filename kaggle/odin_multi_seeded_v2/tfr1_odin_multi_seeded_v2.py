def _ca_residues(path):
    nums=[]
    for line in path.read_text(errors="replace").splitlines():
        if line.startswith("ATOM") and len(line)>=54 and line[12:16].strip()=="CA":
            try:
                nums.append(int(line[22:26]))
            except ValueError:
                continue
    return nums


def materialize_targets():
    """Write the embedded target PDBs to disk and fail fast if anything is wrong.

    This MUST run before the ~12 minute conda/Odin-Multi installation so that a
    packaging regression costs seconds instead of a whole GPU session. The
    2026-10-29 smoke failed only after the full install because the inputs were
    never uploaded by `kaggle kernels push` (script kernels ship `code_file` only).
    """
    print("=== Stage 0: verifying embedded target inputs ===",flush=True)
    missing=[n for n in EXPECTED_TARGET_RESIDUES if n not in EMBEDDED_TARGET_GZ_B64]
    if missing:
        raise SystemExit(
            "FATAL: embedded target payload missing for "+", ".join(sorted(missing))
            +". Run `python scripts/embed_odin_multi_targets.py` and re-push."
        )

    paths={}
    for name,(lo,hi,expected_ca) in EXPECTED_TARGET_RESIDUES.items():
        dest=OUT/name
        try:
            raw=gzip.decompress(base64.b64decode(EMBEDDED_TARGET_GZ_B64[name]))
        except Exception as exc:
            raise SystemExit(f"FATAL: cannot decode embedded payload for {name}: {exc}")

        digest=hashlib.sha256(raw).hexdigest()
        expected=EMBEDDED_TARGET_SHA256.get(name)
        if digest!=expected:
            raise SystemExit(
                f"FATAL: sha256 mismatch for {name}: got {digest}, expected {expected}. "
                "The embedded payload is out of sync with the repository PDB."
            )

        dest.write_bytes(raw)
        nums=_ca_residues(dest)
        if not nums:
            raise SystemExit(f"FATAL: no CA atoms parsed from {name}.")
        if min(nums)!=lo or max(nums)!=hi or len(nums)!=expected_ca:
            raise SystemExit(
                f"FATAL: {name} residue numbering is wrong: CA range "
                f"{min(nums)}-{max(nums)} count {len(nums)}, expected {lo}-{hi} count {expected_ca}. "
                "Hotspot restraints would silently miss their intended residues."
            )
        print(
            f"  OK {name}: {len(raw)} bytes, sha256={digest[:16]}..., "
            f"CA {min(nums)}-{max(nums)} (n={len(nums)}) -> {dest}",
            flush=True,
        )
        paths[name]=dest

    # The mouse model is the human apical frame renumbered +2; the hotspot pairs
    # must line up or the cross-reactivity objective is meaningless.
    human_ca=set(_ca_residues(paths["human_tfr1_apical_189_383.pdb"]))
    mouse_ca=set(_ca_residues(paths["mouse_tfr1_apical_homolog.pdb"]))
    for h,m in ((343,345),(344,346),(347,349),(350,352)):
        if h not in human_ca:
            raise SystemExit(f"FATAL: human hotspot {h} absent from target PDB.")
        if m not in mouse_ca:
            raise SystemExit(f"FATAL: mouse hotspot {m} absent from target PDB.")
    print("  OK all 4 human/mouse hotspot pairs present.",flush=True)
    print("=== Stage 0 passed ===",flush=True)
    return paths



